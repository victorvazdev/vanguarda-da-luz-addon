-- Executa tests/smoke/run.lua (addon completo com a API do jogo simulada).
describe("Teste de fumaça do addon", function()
  it("carrega, importa, sincroniza e envia alertas", function()
    local output, ns, comms, alert = dofile("tests/smoke/run.lua")
    local text = table.concat(output, "\n")
    assert.is_truthy(text:find("erro: Isto não é uma string de exportação", 1, true))
    assert.is_truthy(text:find("Novos: 2", 1, true))
    assert.is_truthy(text:find("eventos salvos: 3", 1, true))
    assert.is_truthy(text:find("recebido da guilda: guild Maren-Forever", 1, true))
    assert.is_nil(ns.db.game) -- dados antigos do calendário do jogo removidos
    -- Início
    assert.is_truthy(text:find("abre no início: true false true", 1, true))
    assert.is_truthy(text:find("mdd: Raide sexta || tragam poções", 1, true))
    assert.is_truthy(text:find("info guilda: Site: |cff7fa8ff|Hvdlurl:https://vanguarda-da-luz.web.app|h", 1, true))
    assert.is_truthy(text:find("Discord: |cff7fa8ff|Hvdlurl:www.discord.gg/abc|hwww.discord.gg/abc|h|r.", 1, true))
    assert.is_truthy(text:find("copiar: true www.discord.gg/abc", 1, true))
    assert.is_truthy(text:find("próximo evento: Raid: Núcleo Derretido", 1, true))
    assert.is_truthy(text:find("ver no calendário: true false sexta, 13 de novembro de 2026", 1, true))
    assert.is_truthy(comms[1]:find("H|1794409200", 1, true))
    assert.is_truthy(comms[2]:find("D|1794409200|VDL1:", 1, true))
    -- lista de presença
    assert.is_truthy(text:find("presença de evento removido apagada: true", 1, true))
    assert.is_truthy(text:find("toggle cancelado: false", 1, true))
    assert.is_truthy(text:find("toggle confirma: true 1 VanguardaDaLuz GUILD NORMAL P|3kTq9ZcV1bWfX7rLm2Pa|1|",
      1, true))
    assert.is_truthy(text:find("confirmados: Maren-Forever,Tester Vaz", 1, true))
    assert.is_truthy(text:find("detalhe presença: |cff%x+Confirmados no jogo %(2%):|r Maren%-Forever, Tester Vaz"))
    assert.is_truthy(text:find("depois do clique: 0 Maren-Forever", 1, true))
    assert.is_truthy(text:find("lista enviada: 1 VanguardaDaLuz GUILD BULK L|VDLP1:", 1, true))
    assert.is_truthy(text:find("confirmados após lista: Ana Clara\n", 1, true))
    assert.is_truthy(text:find(
      "exportação: 1794409200 0 1 evento(s)  ·  1 confirmação(ões)  ·  2 cancelamento(s)", 1, true))
    -- profissões
    assert.is_truthy(text:find("profissões anunciadas: VanguardaDaLuz GUILD NORMAL F|1794410000|1:28:Ferraria",
      1, true))
    assert.is_truthy(text:find("padrão profissões: Mostrar: só online 2", 1, true))
    assert.is_truthy(text:find("contagem profissões: 3 membro(s)  ·  2 online", 1, true))
    assert.is_truthy(text:find("linha 1 Aelin Ashryvrr | Esfolamento  |cffd9cfbb—|r | Couraria", 1, true))
    assert.is_truthy(text:find("| offline", 1, true))
    assert.is_truthy(text:find("linha 2 Maren-Forever | Alquimia  |cfff2c94c40/75|r |  | sussurrar", 1, true))
    assert.is_truthy(text:find("120/150|r | Ferraria  |cfff2c94c88/150|r | sem botão", 1, true))
    assert.is_truthy(text:find("sussurro para: Maren-Forever", 1, true))
    assert.is_truthy(text:find("filtro 1 Tester Vaz", 1, true))
    assert.is_falsy(text:find("filtro 2", 1, true))
    assert.is_truthy(text:find("só online: Mostrar: só online true false", 1, true))
    assert.is_truthy(text:find("níveis enviados: 1 VanguardaDaLuz GUILD BULK K|1:2", 1, true))
    -- abas na janela da guilda
    assert.is_truthy(text:find("abas antes de abrir: false", 1, true))
    assert.is_truthy(text:find("abas da guilda: true true true abaixo de LanguageTab", 1, true))
    assert.is_truthy(text:find("troca de modo: GuildInfoTab -> LanguageTab", 1, true))
    assert.is_truthy(text:find("5º botão da Blizzard fecha o painel: false", 1, true))
    assert.is_truthy(text:find("aba eventos: true true false", 1, true))
    assert.is_truthy(text:find("aba profissões: true false", 1, true))
    assert.is_truthy(text:find("admin abre presenças: true", 1, true))
    assert.is_truthy(text:find("aba da Blizzard fecha o painel: false false", 1, true))
    assert.is_truthy(text:find("outra comunidade: false false true", 1, true))
    -- menu de atalhos do minimapa
    assert.is_truthy(text:find("menu minimapa: true Início,Eventos,Profissões,Sincronizar,Administração,"
      .. "Esconder botão do minimapa", 1, true))
    assert.is_truthy(text:find("atalho eventos: false true true", 1, true))
    assert.is_truthy(text:find("menu fecha sozinho: false", 1, true))
    assert.is_truthy(text:find("menu sem cargo: Início,Eventos,Profissões,Sincronizar,Esconder", 1, true))
    assert.is_truthy(text:find("Somente o Grão Lorde e os Lordes podem importar eventos.", 1, true))
    assert.is_truthy(text:find("importar sem cargo abre: false", 1, true))
    -- alerta de raide
    assert.is_truthy(text:find("prévia: |cff%x+No chat da guilda:|r %[Alerta%] Raide / Núcleo às 20h"))
    assert.is_truthy(text:find("Aguarde 30 s para enviar outro alerta.", 1, true))
    assert.is_truthy(text:find("Comunicação restrita no momento", 1, true))
    assert.is_truthy(text:find("alertas enviados: 1", 1, true))
    assert.is_truthy(comms[#comms]:find("VanguardaDaLuz GUILD ALERT A|", 1, true))
    assert.are.same({ "GUILD [Alerta] Raide / Núcleo às 20h" }, alert.chat)
    assert.are.same({ "Tester Vaz: Raide / Núcleo às 20h", "Maren-Forever: Entrem já" }, alert.warnings)
    assert.are.equal(2, alert.sounds)
    -- fora da guilda
    assert.is_truthy(text:find("boas-vindas: true https://discord.gg/uGyPjtEsBw calendário: false", 1, true))
    assert.is_truthy(text:find("alerta fora da guilda abre boas-vindas: true", 1, true))
    assert.is_truthy(text:find("fora da guilda: dados ignorados envios 0", 1, true))
  end)
end)
